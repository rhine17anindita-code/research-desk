import { ANSWER_STATE_LABELS, DIMENSION_LABELS } from "@/lib/types";

const STATE_STYLE: Record<string, string> = {
  unexamined: "border-line text-muted",
  established: "border-ok/30 bg-ok-soft text-ok",
  partial: "border-warn/30 bg-warn-soft text-warn",
  contested: "border-bad/30 bg-bad-soft text-bad",
  "needs-investigation": "border-accent/30 bg-accent-soft text-accent",
  open: "border-line-strong text-ink-2",
  insufficient: "border-line-strong bg-surface-2 text-muted",
  user: "border-line text-ink-2",
};

export function StateBadge({ state }: { state: string }) {
  return (
    <span className={`inline-flex shrink-0 items-center rounded-full border px-2 py-px text-[11px] font-medium ${STATE_STYLE[state] ?? STATE_STYLE.unexamined}`}>
      {ANSWER_STATE_LABELS[state] ?? (state === "user" ? "Your finding" : state)}
    </span>
  );
}

export function DimensionLabel({ dimension }: { dimension: string | null }) {
  if (!dimension) return null;
  return <span className="text-[11px] font-medium uppercase tracking-[0.06em] text-muted">{DIMENSION_LABELS[dimension] ?? dimension}</span>;
}

/** Provenance marker: separates external sources, the user's own work and AI output. */
export function OriginBadge({ origin }: { origin: string }) {
  if (origin === "ai") return <span className="rounded bg-ai-soft px-1.5 py-px text-[10.5px] font-semibold uppercase tracking-wide text-ai" title="Generated by AI">AI</span>;
  if (origin === "assistant") return <span className="rounded bg-ai-soft px-1.5 py-px text-[10.5px] font-semibold uppercase tracking-wide text-ai" title="Saved from the assistant">Assistant</span>;
  if (origin === "user") return <span className="rounded bg-surface-2 px-1.5 py-px text-[10.5px] font-semibold uppercase tracking-wide text-ink-2" title="Written by you">You</span>;
  return null;
}

const KIND_STYLE: Record<string, string> = {
  fact: "text-ok",
  interpretation: "text-ai",
  allegation: "text-bad",
  prediction: "text-warn",
  hypothesis: "text-accent",
};

export function ClaimKind({ kind }: { kind: string }) {
  return <span className={`text-[10.5px] font-semibold uppercase tracking-wide ${KIND_STYLE[kind] ?? "text-muted"}`}>{kind}</span>;
}
